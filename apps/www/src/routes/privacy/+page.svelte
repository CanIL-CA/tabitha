<h1>Privacy Policy</h1>
<p class="page-dek">Last updated: October 27, 2026</p>

<div class="page-body">
	<p>
		This policy covers tabitha.bible and its subdomains (editor, copilot, ontology, sources, targets,
		and survey .tabitha.bible) — together, "the TaBiThA site." TaBiThA is a research and innovation
		project of <a href="https://www.canil.ca">CanIL</a>.
	</p>

	<h2>Information we collect</h2>
	<p>
		Most of these pages don't ask you to create an account or submit personal information. Like
		virtually every website, standard connection logs (IP address, browser/device type, pages
		requested, timestamps) are generated automatically by our hosting provider, Cloudflare, for
		security and operational purposes such as detecting abuse and diagnosing errors. We don't
		separately collect, sell, or use this data for advertising.
	</p>

	<h2>Account data (ontology)</h2>
	<p>
		ontology.tabitha.bible lets members of the project's linguistics team sign in with Google to
		access editing tools reserved for authorized contributors. Signing in shares your name, email
		address, and profile picture with us, as provided by your Google account. We use this only to
		identify you, attribute the edits you make, and check whether your account is authorized for
		those editing tools — never for marketing, and never shared with third parties beyond the
		processors on this page. Signing in also records a session (the browser it came from, not your
		IP address) and stores the sign-in tokens Google issues, encrypted; both are used only to keep
		you signed in. We keep this data for as long as your account remains active; contact us below
		to have it deleted.
	</p>

	<h2>Survey responses (survey)</h2>
	<p>
		survey.tabitha.bible collects reviews from people the project invites by link, such as
		translation consultants comparing two versions of a tool's output. It stores the name you
		type, your answers, and your comments, so the project can read the results and know whose
		scores are whose. Only the people who ran the survey see the results. A cookie on that survey's
		link remembers your answers in your browser, so you can come back later; it holds a random
		identifier, nothing about you. Contact us below to have your responses deleted.
	</p>

	<h2>Cookies and tracking</h2>
	<p>
		Outside of the sign-in session ontology.tabitha.bible sets for signed-in users, the cookie it
		sets so each page reads data at least as recent as the last one you loaded (it holds a database
		version marker, nothing about you), and the cookie survey.tabitha.bible sets to keep your
		answers, this site doesn't use cookies, run third-party analytics scripts, or use any third-party advertising or
		tracking pixels.
	</p>

	<h2>Anonymous feature usage</h2>
	<p>
		To learn which features are worth improving, the ontology, sources, targets, editor, and
		copilot apps count a few anonymous usage events:
	</p>
	<ul>
		<li>
			searches in ontology, sources, and targets — the search terms entered, the options chosen, and
			how many results came back;
		</li>
		<li>
			copilot runs — the settings chosen (mode, language, level, and which language-profile options
			were changed), the book, how many verses were requested, and whether any failed;
		</li>
		<li>
			editor checks and AI Assist requests — whether they succeeded and how many errors or warnings
			the checker found, but not the text itself;
		</li>
		<li>which color theme is active, once per browser session in each app.</li>
	</ul>
	<p>
		These events carry no account, IP address, cookie, or other identifier, so they can't be tied to
		you or linked across visits. They're stored with Cloudflare, our hosting provider, and aren't
		shared with anyone else.
	</p>

	<h2>AI-assisted translation tooling</h2>
	<p>
		The copilot app (copilot.tabitha.bible) sends translation and linguistic content to Google's
		Vertex AI service to generate AI-assisted drafting suggestions for the project's translation
		team. That content is Bible-translation material, not visitor personal information, and is
		processed under Google's Vertex AI terms.
	</p>

	<h2>Other third parties</h2>
	<ul>
		<li><strong>Cloudflare</strong> hosts and serves every page on this domain.</li>
		<li>
			<strong>Google</strong> provides the Sign in with Google flow ontology.tabitha.bible uses for
			account authentication, governed by Google's own privacy policy.
		</li>
		<li>
			<strong>GitHub</strong> hosts the project's public source code and issue tracker; interacting
			with the project there is governed by GitHub's own privacy policy.
		</li>
		<li>Links to external sites (canil.ca, academic papers, etc.) are outside our control.</li>
	</ul>

